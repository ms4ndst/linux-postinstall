#!/usr/bin/env python3
"""Generate Neovim colorschemes matching this rice's polybar/rofi/kitty/
VS Code themes.

Reuses generate-vscode-themes.py's own THEMES list, parse_theme_colors()
and resolve()/ROLE_CHAINS (loaded by file path, same convention as
generate-gtk-themes.py - a hyphenated filename can't be `import`ed
directly) rather than a second, separately-maintained copy of the same
per-theme color-resolution logic.

Writes each theme as a plain, dependency-free Neovim colorscheme file at
~/.config/nvim/colors/rice-<name>.lua (Neovim's own `colors/` runtimepath
convention - no plugin manager or `require()` wiring needed, `:colorscheme
rice-<name>` just finds it). polybar-theme.sh copies the picked one over
colors/current.lua and pushes `:colorscheme current` into every already-
open nvim instance via its RPC socket (see NVIM_CURRENT/serverstart there
and in lua/config/autocmds.lua) - the same "generate all themes up front,
activate by copy" split this rice already uses for kitty/starship/dunst/
rofi, not a new pattern.

Only the 28 base themes are covered, not their -square counterparts -
square-vs-rounded is a polybar-bar/rofi-window corner-radius concept with
no Neovim equivalent, so a theme and its square twin would produce
byte-identical colorscheme output (matching generate-vscode-themes.py's
and generate-gtk-themes.py's own existing base-only scope).

Usage:
    python3 generate-nvim-themes.py

Then either run polybar-theme.sh <name> (applies it as part of the normal
desktop theme switch) or, inside Neovim, ':colorscheme rice-<name>'
directly. Re-run any time after editing a polybar theme's [colors] block
to regenerate (idempotent - always overwrites its own output files).
"""
import importlib.util
import os

_here = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location(
    "generate_vscode_themes", os.path.join(_here, "generate-vscode-themes.py")
)
_vscode_gen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_vscode_gen)

THEMES = _vscode_gen.THEMES
LIGHT_THEMES = _vscode_gen.LIGHT_THEMES
POLYBAR_THEMES_DIR = _vscode_gen.POLYBAR_THEMES_DIR
parse_theme_colors = _vscode_gen.parse_theme_colors
resolve = _vscode_gen.resolve

NVIM_CONFIG_DIR = os.path.expanduser("~/.config/nvim")
NVIM_COLORS_DIR = os.path.join(NVIM_CONFIG_DIR, "colors")
NVIM_PLUGINS_DIR = os.path.join(NVIM_CONFIG_DIR, "lua", "plugins")
NVIM_AUTOCMDS_PATH = os.path.join(NVIM_CONFIG_DIR, "lua", "config", "autocmds.lua")
NVIM_NORDIC_PLUGIN = os.path.join(NVIM_PLUGINS_DIR, "nordic.lua")
NVIM_RICE_PLUGIN = os.path.join(NVIM_PLUGINS_DIR, "rice-theme.lua")

# Marker substring used to detect an already-patched autocmds.lua (idempotent
# re-runs must not append a second copy).
AUTOCMD_MARKER = "/tmp/nvim-mgns-"

RICE_THEME_PLUGIN = """-- Colorscheme is generated by generate-nvim-themes.py (repo root, from
-- this rice's own polybar theme [colors] blocks) and switched live by
-- polybar-theme.sh, which copies the picked colors/rice-<name>.lua over
-- colors/current.lua. No plugin needed for "current" itself - it's a
-- plain Neovim colorscheme file, found on runtimepath like any other -
-- this just tells LazyVim to load it at startup instead of its own
-- default (tokyonight).
return {
  { "LazyVim/LazyVim", opts = { colorscheme = "current" } },
}
"""

AUTOCMD_SNIPPET = """
-- Own RPC server per instance, named like kitty's listen_on sockets
-- (/tmp/kitty-mgns-<PID>, see kitty.conf), so polybar-theme.sh can push a
-- live `:colorscheme current` into every already-open Neovim window on a
-- desktop theme switch - Neovim has no gsettings-style "theme changed"
-- signal an already-running instance reacts to on its own, unlike kitty's
-- `kitty @` or GTK's live re-theming, so this is the same explicit "loop
-- over sockets" mechanism as kitty's, not a copy-paste - Neovim needs it,
-- GTK doesn't. This file only loads on VeryLazy (see header above), by
-- which point an interactive session's UI is already attached, so the
-- nvim_list_uis() check below reliably tells apart a real terminal session
-- from a headless invocation (e.g. `nvim --headless +Lazy! sync` during
-- plugin install) - no interactive session to retint there, and starting a
-- server would just leak a socket no switch will ever reach.
if #vim.api.nvim_list_uis() > 0 then
  pcall(vim.fn.serverstart, "{marker}" .. vim.fn.getpid())
end
""".format(marker=AUTOCMD_MARKER)


def build_palette(c):
    base = c["base"]
    mantle = c["mantle"]
    surface0 = c.get("surface0", mantle)
    surface1 = c.get("surface1", surface0)
    text = c["text"]
    subtext = c["subtext"]
    return {
        "base": base,
        "mantle": mantle,
        "surface0": surface0,
        "surface1": surface1,
        "text": text,
        "subtext": subtext,
        "accent": resolve(c, "accent"),
        "red": resolve(c, "red"),
        "green": resolve(c, "green"),
        "yellow": resolve(c, "yellow"),
        "blue": resolve(c, "blue"),
        "cyan": resolve(c, "cyan"),
        "orange": resolve(c, "orange"),
        "pink": resolve(c, "pink"),
    }


# Ordered (group, opts) pairs, opts using palette role names resolved
# against the `p` table written into the Lua output (fg/bg/bold/italic/
# undercurl only - the small subset every group below actually needs).
# Covers core editor chrome + classic syntax groups + diagnostics/diff/
# gitsigns + the handful of LazyVim-default plugin groups (Telescope,
# neo-tree, WhichKey) most visibly on-screen, then links Neovim's
# built-in Treesitter @captures onto those same classic syntax groups -
# matching generate-vscode-themes.py's own scope (core editor + a
# reasonable, not exhaustive, token set), not a second design.
