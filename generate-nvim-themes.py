def lua_bool(v):
    return "true" if v else "false"


def render_theme(name, c):
    p = build_palette(c)
    groups, links = build_groups(p)
    background = "light" if name in LIGHT_THEMES else "dark"

    lines = []
    lines.append(f"-- Rice theme \"{name}\" - generated by generate-nvim-themes.py from")
    lines.append(f"-- ~/.config/polybar/themes/{name}.ini's own [colors] block. Do not edit")
    lines.append("-- by hand - re-run the generator after changing that file instead.")
    lines.append('vim.cmd("hi clear")')
    lines.append('if vim.fn.exists("syntax_on") == 1 then')
    lines.append('  vim.cmd("syntax reset")')
    lines.append("end")
    lines.append(f'vim.o.background = "{background}"')
    lines.append(f'vim.g.colors_name = "rice-{name}"')
    lines.append("")
    lines.append("local hl = vim.api.nvim_set_hl")
    lines.append("")

    for group, opts in groups:
        parts = []
        for key in ("fg", "bg", "sp"):
            if key in opts:
                parts.append(f'{key} = "{opts[key]}"')
        for key in ("bold", "italic", "underline", "undercurl"):
            if opts.get(key):
                parts.append(f"{key} = {lua_bool(True)}")
        lines.append(f'hl(0, "{group}", {{ {", ".join(parts)} }})')

    lines.append("")
    for capture, target in links.items():
        lines.append(f'hl(0, "{capture}", {{ link = "{target}" }})')
    lines.append("")

    return "\n".join(lines)


# Wires an already-installed LazyVim config (e.g. from install_lazyvim in
# post-install-fedora.sh/post-install-opensuse.sh) into the rice system:
# drops the fixed Nordic default in favor of "current", and adds the
# RPC-server autocmd polybar-theme.sh's live-switch step depends on. A
# no-op (with an explanatory skip message, not a hard failure) if ~/.config/
# nvim doesn't exist - Neovim/LazyVim setup is a separate, independent,
# opt-in step this script doesn't own or require.
def wire_nvim_config():
    if not os.path.isdir(NVIM_CONFIG_DIR):
        print(f"skip Neovim wiring: {NVIM_CONFIG_DIR} not found (set up LazyVim first)")
        return

    os.makedirs(NVIM_PLUGINS_DIR, exist_ok=True)
    if os.path.isfile(NVIM_NORDIC_PLUGIN):
        os.remove(NVIM_NORDIC_PLUGIN)
        print(f"removed {NVIM_NORDIC_PLUGIN} (superseded by rice-theme.lua)")
    with open(NVIM_RICE_PLUGIN, "w", encoding="utf-8") as f:
        f.write(RICE_THEME_PLUGIN)
    print(f"wrote {NVIM_RICE_PLUGIN}")

    os.makedirs(os.path.dirname(NVIM_AUTOCMDS_PATH), exist_ok=True)
    existing = ""
    if os.path.isfile(NVIM_AUTOCMDS_PATH):
        with open(NVIM_AUTOCMDS_PATH, encoding="utf-8") as f:
            existing = f.read()
    if AUTOCMD_MARKER in existing:
        print(f"{NVIM_AUTOCMDS_PATH} already has the RPC-server autocmd, leaving it")
    else:
        with open(NVIM_AUTOCMDS_PATH, "a", encoding="utf-8") as f:
            f.write(AUTOCMD_SNIPPET)
        print(f"appended RPC-server autocmd to {NVIM_AUTOCMDS_PATH}")

    # Seed an initial current.lua only if one doesn't exist yet - never
    # stomp whatever theme the user (or a previous run) already picked.
    current_path = os.path.join(NVIM_COLORS_DIR, "current.lua")
    if not os.path.isfile(current_path):
        seed_path = os.path.join(NVIM_COLORS_DIR, "rice-catppuccin-mocha.lua")
        if os.path.isfile(seed_path):
            with open(seed_path, encoding="utf-8") as f:
                content = f.read()
            with open(current_path, "w", encoding="utf-8") as f:
                f.write(content)
            print(f"seeded {current_path} from rice-catppuccin-mocha.lua (run polybar-theme.sh <name> to switch)")


def main():
    os.makedirs(NVIM_COLORS_DIR, exist_ok=True)
    written = 0
    for name in THEMES:
        ini_path = os.path.join(POLYBAR_THEMES_DIR, f"{name}.ini")
        if not os.path.isfile(ini_path):
            print(f"skip {name}: {ini_path} not found")
            continue
        c = parse_theme_colors(ini_path)
        out_path = os.path.join(NVIM_COLORS_DIR, f"rice-{name}.lua")
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(render_theme(name, c))
        written += 1
        print(f"wrote {out_path}")

    print(f"\n{written} colorschemes written to {NVIM_COLORS_DIR}")

    wire_nvim_config()

    print("\nRun polybar-theme.sh <name> to apply one, or ':colorscheme rice-<name>' inside Neovim.")


if __name__ == "__main__":
    main()
